class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("areca_lang") || "kn"; // Default Kannada for farmers
    document.addEventListener("DOMContentLoaded", () => {
      this.applyTranslations();
    });
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem("areca_lang", lang);
      this.applyTranslations();
      document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
    }
  }

  t(key) {
    if (translations[this.currentLang] && translations[this.currentLang][key]) {
      return translations[this.currentLang][key];
    }
    return translations.en[key] || key;
  }

  applyTranslations() {
    // Translate textContent and placeholders
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const trans = this.t(key);
      if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
        el.setAttribute("placeholder", trans);
      } else if (el.tagName === "OPTION") {
        el.textContent = trans;
      } else {
        el.textContent = trans;
      }
    });

    // Translate tooltips and titles
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      el.setAttribute("title", this.t(key));
    });

    // Update toggle button text to show the OTHER language option
    const langBtn = document.getElementById("langToggleBtn");
    if (langBtn) {
      langBtn.textContent = this.currentLang === "kn" ? "English" : "ಕನ್ನಡ";
      langBtn.setAttribute("title", this.currentLang === "kn" ? "Switch to English" : "ಕನ್ನಡಕ್ಕೆ ಬದಲಾಯಿಸಿ");
    }

    // Update HTML lang attribute
    document.documentElement.lang = this.currentLang;
  }
}

const i18n = new I18nManager();
window.i18n = i18n;
